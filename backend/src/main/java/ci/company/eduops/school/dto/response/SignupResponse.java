package ci.company.eduops.school.dto.response;

import java.util.UUID;

/** Returned by a successful signup: the new school plus a ready-to-use session. */
public class SignupResponse {

    private UUID schoolId;
    private String schoolCode;
    private String schoolName;
    private UUID userId;
    private String email;
    private String fullName;
    private UUID academicYearId;
    private String academicYearCode;
    private String accessToken;
    private String refreshToken;
    private long expiresIn;
    /** The signup only creates the shell; the wizard fills in the structure. */
    private boolean onboardingRequired = true;

    public UUID getSchoolId() {
        return schoolId;
    }

    public void setSchoolId(UUID schoolId) {
        this.schoolId = schoolId;
    }

    public String getSchoolCode() {
        return schoolCode;
    }

    public void setSchoolCode(String schoolCode) {
        this.schoolCode = schoolCode;
    }

    public String getSchoolName() {
        return schoolName;
    }

    public void setSchoolName(String schoolName) {
        this.schoolName = schoolName;
    }

    public UUID getUserId() {
        return userId;
    }

    public void setUserId(UUID userId) {
        this.userId = userId;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getFullName() {
        return fullName;
    }

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }

    public UUID getAcademicYearId() {
        return academicYearId;
    }

    public void setAcademicYearId(UUID academicYearId) {
        this.academicYearId = academicYearId;
    }

    public String getAcademicYearCode() {
        return academicYearCode;
    }

    public void setAcademicYearCode(String academicYearCode) {
        this.academicYearCode = academicYearCode;
    }

    public String getAccessToken() {
        return accessToken;
    }

    public void setAccessToken(String accessToken) {
        this.accessToken = accessToken;
    }

    public String getRefreshToken() {
        return refreshToken;
    }

    public void setRefreshToken(String refreshToken) {
        this.refreshToken = refreshToken;
    }

    public long getExpiresIn() {
        return expiresIn;
    }

    public void setExpiresIn(long expiresIn) {
        this.expiresIn = expiresIn;
    }

    public boolean isOnboardingRequired() {
        return onboardingRequired;
    }

    public void setOnboardingRequired(boolean onboardingRequired) {
        this.onboardingRequired = onboardingRequired;
    }
}
